#!/usr/bin/env python3
"""
Render the Orange OS wordmark and its Chinese slogan into 1-bit bitmaps that
the boot sector can blit.

There is no font library and no PIL in this image, so the glyphs are rasterized
by ffmpeg's drawtext filter (which does have freetype) and then thresholded.
Everything is emitted as NASM data: one label per piece of text, with its
width and height, so boot.asm can lay the screen out from the real numbers
instead of from guesses.

The bitmaps are 1 bit per pixel, MSB first, every row padded to a byte.
"""

import subprocess
import sys
import tempfile
import os

DEJA_VU = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
NOTO_CJK = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"

# (label, text, font, size, note)
ITEMS = [
    ("orange", "Orange", DEJA_VU, 108, "the wordmark, painted orange"),
    ("os", "OS", DEJA_VU, 108, "the wordmark, painted blue"),
    ("slogan", "橙光随行，流畅无界", NOTO_CJK, 40, "橙光随行，流畅无界"),
    ("brand", "CHENG GUANG OS  ·  NUBASY", DEJA_VU, 20, "brand line"),
]

THRESHOLD = 96


def render(text, font, size):
    """Return (w, h, rows) where rows is a list of byte-packed 1-bit rows."""
    # Generous canvas; drawtext clips silently if it is too small.
    canvas_w = size * len(text) + size * 2
    canvas_h = int(size * 1.8) + size

    draw = (
        f"color=black:s={canvas_w}x{canvas_h},"
        f"drawtext=fontfile={font}:text={text}:fontcolor=white:"
        f"fontsize={size}:x={size // 2}:y={size // 4}"
    )

    with tempfile.NamedTemporaryFile(suffix=".raw", delete=False) as tmp:
        path = tmp.name

    subprocess.run(
        ["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-f", "lavfi", "-i", draw,
         "-frames:v", "1", "-pix_fmt", "gray", "-f", "rawvideo", path],
        check=True,
    )

    with open(path, "rb") as fh:
        data = fh.read()
    os.unlink(path)

    if len(data) != canvas_w * canvas_h:
        sys.exit(f"mkfont: expected {canvas_w * canvas_h} bytes, got {len(data)}")

    # Threshold, then crop to the bounding box of the ink.
    ink = [[1 if data[y * canvas_w + x] > THRESHOLD else 0
            for x in range(canvas_w)] for y in range(canvas_h)]

    rows_with_ink = [y for y, r in enumerate(ink) if any(r)]
    if not rows_with_ink:
        sys.exit(f"mkfont: nothing rendered for {text!r}")
    cols_with_ink = [x for x in range(canvas_w) if any(ink[y][x] for y in rows_with_ink)]

    y0, y1 = rows_with_ink[0], rows_with_ink[-1]
    x0, x1 = cols_with_ink[0], cols_with_ink[-1]
    h, w = y1 - y0 + 1, x1 - x0 + 1

    packed = []
    stride = (w + 7) // 8
    for y in range(y0, y1 + 1):
        row = ink[y][x0:x1 + 1]
        byte = 0
        out = bytearray()
        for i, px in enumerate(row):
            byte = (byte << 1) | px
            if i % 8 == 7:
                out.append(byte)
                byte = 0
        if len(row) % 8:
            byte <<= 8 - (len(row) % 8)
            out.append(byte)
        assert len(out) == stride
        packed.append(bytes(out))

    return w, h, packed


def emit_c(fh, label, comment, w, h, packed):
    flat = b"".join(packed)
    fh.write(f"/* {label}: {comment} ({w}x{h}, {len(flat)} bytes) */\n")
    fh.write(f"static const unsigned char bits_{label}[] = {{\n")
    for off in range(0, len(flat), 16):
        fh.write("    " + ", ".join(f"0x{b:02X}" for b in flat[off:off + 16]) + ",\n")
    fh.write("};\n")
    fh.write(f"const struct glyph glyph_{label} = {{ bits_{label}, {w}, {h} }};\n\n")


def emit_h(fh):
    fh.write("/* Generated by tools/mkfont.py -- do not edit by hand. */\n")
    fh.write("#ifndef FONTS_H\n#define FONTS_H\n\n")
    fh.write("struct glyph {\n")
    fh.write("    const unsigned char *bits; /* 1bpp, MSB first, rows byte-aligned */\n")
    fh.write("    unsigned int w, h;\n")
    fh.write("};\n\n")
    for label, _t, _f, _s, _c in ITEMS:
        fh.write(f"extern const struct glyph glyph_{label};\n")
    fh.write("\n#endif /* FONTS_H */\n")


def main():
    out_c = sys.argv[1] if len(sys.argv) > 1 else "build/fonts.c"
    out_h = out_c[:-2] + ".h"
    total = 0
    with open(out_h, "w", encoding="utf-8") as fh:
        emit_h(fh)
    with open(out_c, "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/mkfont.py -- do not edit by hand. */\n")
        fh.write('#include "fonts.h"\n\n')
        for label, text, font, size, comment in ITEMS:
            w, h, packed = render(text, font, size)
            emit_c(fh, label, comment, w, h, packed)
            total += len(b"".join(packed))
            print(f"  {label:8s} {w:4d}x{h:<4d} {len(b''.join(packed)):6d} bytes")
    print(f"mkfont: {out_c} + {out_h} ({total} bytes of bitmaps)")


if __name__ == "__main__":
    main()
